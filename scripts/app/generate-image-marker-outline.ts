import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { Resvg } from "@resvg/resvg-js";
import { getImageMarkerEdgeDistance, MAP_THUMBNAIL_SIZE } from "../../gears/route-story/common/src/tinkers/images";
import type { ImageMarkerShape } from "../../gears/route-story/common/src/model";

const size = MAP_THUMBNAIL_SIZE + 32;
const radius = MAP_THUMBNAIL_SIZE / 2;
const renderOutline = (shape: ImageMarkerShape): string => {
    const alphaAt = (x: number, y: number): number => {
        const edgeDistance = getImageMarkerEdgeDistance(x - size / 2, y - size / 2, radius, shape);
        return Math.max(0, Math.min(1, 0.75 + edgeDistance / 8));
    };
    assert.equal(alphaAt(size / 2, size / 2), 1);
    assert.equal(alphaAt(0, 0), 0);
    assert.equal(alphaAt(size / 2 + radius, size / 2), 0.75);
    const pixels: string[] = [];
    for (let vertical = 0; vertical < size; vertical++) {
        for (let horizontal = 0; horizontal < size; horizontal++) {
            const alpha = alphaAt(horizontal + 0.5, vertical + 0.5);
            if (alpha > 0) {
                pixels.push(
                    `<rect x="${horizontal}" y="${vertical}" width="1" height="1" fill-opacity="${alpha.toFixed(4)}"/>`,
                );
            }
        }
    }
    const png = new Resvg(
        `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}">${pixels.join("")}</svg>`,
    )
        .render()
        .asPng();
    return `data:image/png;base64,${png.toString("base64")}`;
};
const shapes: ImageMarkerShape[] = ['circle', 'square', 'hexagon'];
fs.writeFileSync(
    path.resolve(__dirname, "../../gears/route-story/common/src/layer-specification/images/image-marker-outline.ts"),
    `// Generated by scripts/app/generate-image-marker-outline.ts.\nexport const IMAGE_MARKER_OUTLINE_SIZE = ${size};\nexport const IMAGE_MARKER_OUTLINE_SDF_URIS = {\n${shapes.map((shape) => `    ${shape}: "${renderOutline(shape)}",`).join('\n')}\n};\n`,
);
